export function slugifyTool(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9.]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export const CATALOG_URLS: Record<string, string> = Object.fromEntries(
  CATALOG.flatMap((c) => c.tools.map((tool) => [tool.name, tool.url]))
);

export function findCatalogTool(name: string): CatalogTool | undefined {
  const key = name.toLowerCase();
  for (const category of CATALOG) {
    const match = category.tools.find((tool) => tool.name.toLowerCase() === key);
    if (match) return match;
  }
  return undefined;
}
