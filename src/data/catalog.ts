/**
 * Structured tool catalog used to generate data-driven comparison pages.
 *
 * Every pair of tools inside the same category becomes a comparison page via
 * `npm run generate:catalog`. Pairs that already have a hand-written comparison
 * in src/content/comparisons are skipped.
 *
 * Pricing is described as a model (not dollar amounts) so pages do not go
 * stale when vendors change list prices.
 */

export type License = 'yes' | 'no' | 'core' | 'source';

export interface CatalogTool {
  name: string;
  url: string;
  tagline: string;
  bestFor: string;
  pricing: string;
  freeTier: boolean;
  license: License;
  hosting: string;
  popularity: number;
  pros: string[];
  cons: string[];
}

export interface CatalogCategory {
  name: string;
  tools: CatalogTool[];
}

export const LICENSE_LABELS: Record<License, string> = {
  yes: 'Open source',
  no: 'Proprietary',
  core: 'Open-core',
  source: 'Source-available',
};

const P = {
  freemium: 'Free tier with paid plans',
  oss: 'Free and open source',
  ossCloud: 'Free open source; paid managed cloud',
  usage: 'Pay-as-you-go usage pricing',
  usageFree: 'Free tier, then usage-based pricing',
  paid: 'Paid plans; free trial available',
  enterprise: 'Custom enterprise pricing',
  tx: 'Per-transaction fees, no monthly fee',
};

const H = {
  cloud: 'Managed cloud',
  both: 'Self-hosted or managed cloud',
  self: 'Self-hosted',
  lib: 'Library / framework in your stack',
  desktop: 'Desktop app',
  local: 'Runs locally',
};

function t(
  name: string,
  url: string,
  tagline: string,
  bestFor: string,
  pricing: string,
  freeTier: boolean,
  license: License,
  hosting: string,
  popularity: number,
  pros: string[],
  cons: string[]
): CatalogTool {
  return { name, url, tagline, bestFor, pricing, freeTier, license, hosting, popularity, pros, cons };
}

